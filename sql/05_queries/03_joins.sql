Question    : Orders with Customer Details
Description : Retrieves each order along with the customer information who
              placed the order.
===============================================================================
*/

SELECT
    o.order_id,
    c.customer_unique_id,
    c.customer_city,
    c.customer_state,
    o.order_status,
    o.order_purchase_timestamp
FROM customers AS c
INNER JOIN orders AS o
