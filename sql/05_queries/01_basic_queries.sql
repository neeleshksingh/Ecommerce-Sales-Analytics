------------------------------------------------------------------------------
-- 1. Display all customers
------------------------------------------------------------------------------

SELECT *
FROM customers;

------------------------------------------------------------------------------
-- 2. Display all orders
------------------------------------------------------------------------------

SELECT *
FROM orders;

------------------------------------------------------------------------------
-- 3. Display all products
------------------------------------------------------------------------------

SELECT *
FROM products;

------------------------------------------------------------------------------
-- 4. Display all sellers
------------------------------------------------------------------------------

SELECT *
FROM sellers;

------------------------------------------------------------------------------
-- 5. Display all payments
------------------------------------------------------------------------------

SELECT *
FROM order_payments;

------------------------------------------------------------------------------
-- 6. Total number of customers
------------------------------------------------------------------------------

SELECT COUNT(*) AS total_customers
FROM customers;

------------------------------------------------------------------------------
-- 7. Total number of orders
------------------------------------------------------------------------------

SELECT COUNT(*) AS total_orders
FROM orders;

------------------------------------------------------------------------------
-- 8. Total number of products
------------------------------------------------------------------------------

SELECT COUNT(*) AS total_products
FROM products;

------------------------------------------------------------------------------
-- 9. Total number of sellers
------------------------------------------------------------------------------

SELECT COUNT(*) AS total_sellers
FROM sellers;

------------------------------------------------------------------------------
-- 10. Total Revenue
------------------------------------------------------------------------------

SELECT
    ROUND(SUM(price), 2) AS total_revenue
FROM order_items;