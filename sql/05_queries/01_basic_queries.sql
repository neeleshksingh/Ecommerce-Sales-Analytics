------------------------------------------------------------------------------

SELECT *
FROM vw_orders;

------------------------------------------------------------------------------
-- 3. Display all products
------------------------------------------------------------------------------

SELECT *
FROM vw_products;

------------------------------------------------------------------------------
-- 4. Display all sellers
------------------------------------------------------------------------------

SELECT *
FROM vw_sellers;

------------------------------------------------------------------------------
-- 5. Display all payments
------------------------------------------------------------------------------

SELECT *
FROM vw_payments;

------------------------------------------------------------------------------
-- 6. Display all deliveries
------------------------------------------------------------------------------

SELECT *
FROM vw_delivery;

------------------------------------------------------------------------------
-- 7. Display all sales
------------------------------------------------------------------------------

SELECT *
FROM vw_sales;

------------------------------------------------------------------------------
-- 8. Display RFM metrics
------------------------------------------------------------------------------

SELECT *
FROM vw_rfm;

------------------------------------------------------------------------------
-- 9. Total customers
------------------------------------------------------------------------------

SELECT
    COUNT(*) AS total_customers
FROM vw_customers;

------------------------------------------------------------------------------
-- 10. Total orders
------------------------------------------------------------------------------

SELECT
    COUNT(*) AS total_orders
FROM vw_orders;

------------------------------------------------------------------------------
-- 11. Total products
------------------------------------------------------------------------------

SELECT
    COUNT(*) AS total_products
FROM vw_products;

------------------------------------------------------------------------------
-- 12. Total sellers
------------------------------------------------------------------------------

SELECT
    COUNT(*) AS total_sellers
FROM vw_sellers;

------------------------------------------------------------------------------
-- 13. Total revenue
------------------------------------------------------------------------------

SELECT
    ROUND(SUM(price), 2) AS total_revenue
FROM vw_sales;

------------------------------------------------------------------------------
-- 14. Average product price
------------------------------------------------------------------------------

SELECT
    ROUND(AVG(price), 2) AS average_product_price
FROM vw_sales;

------------------------------------------------------------------------------
-- 15. Minimum product price
------------------------------------------------------------------------------

SELECT
    MIN(price) AS minimum_product_price
FROM vw_sales;

------------------------------------------------------------------------------
-- 16. Maximum product price
------------------------------------------------------------------------------

SELECT
    MAX(price) AS maximum_product_price
FROM vw_sales;

------------------------------------------------------------------------------
-- 17. Earliest purchase date
------------------------------------------------------------------------------

SELECT
    MIN(order_purchase_timestamp) AS first_purchase_date
FROM vw_sales;

------------------------------------------------------------------------------
-- 18. Latest purchase date
------------------------------------------------------------------------------

SELECT
    MAX(order_purchase_timestamp) AS latest_purchase_date
FROM vw_sales;

------------------------------------------------------------------------------
-- 19. Total freight cost
------------------------------------------------------------------------------

SELECT
    ROUND(SUM(freight_value), 2) AS total_freight_cost
FROM vw_sales;

------------------------------------------------------------------------------
-- 20. Total number of order items sold
------------------------------------------------------------------------------

SELECT
    COUNT(*) AS total_order_items
FROM vw_sales;