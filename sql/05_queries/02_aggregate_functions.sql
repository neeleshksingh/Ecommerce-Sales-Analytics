/*
===============================================================================
Question    : Monthly Revenue
Description : Calculates the total revenue generated for each month and
              displays the monthly revenue in chronological order.
===============================================================================
*/

SELECT
    DATE_TRUNC('month', order_purchase_timestamp) AS sales_month,

    ROUND(SUM(price), 2) AS total_revenue

FROM vw_sales

GROUP BY
    sales_month

ORDER BY
    sales_month;

