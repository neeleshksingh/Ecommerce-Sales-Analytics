/*
===============================================================================
Question    : Revenue by Product Category
Description : Calculates the total revenue generated by each product category
              and displays the categories in descending order of revenue.
===============================================================================
*/

SELECT
    product_category_name_english AS product_category,
    ROUND(SUM(price), 2) AS total_revenue

FROM vw_sales

GROUP BY
    product_category_name_english

ORDER BY
    total_revenue DESC;


